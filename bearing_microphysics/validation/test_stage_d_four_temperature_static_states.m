end

function test_strict_continuation_resume_and_finalize(baseline)
initial = validate_stage_d_four_temperature_results(struct('results',baseline));
assert(initial.passed && initial.next_temperature_C == 50);

assert_error(@() update_stage_d_canonical_results( ...
    baseline,mock_state(80,50,baseline),'stage-d-test'), ...
    'StageD:ContinuationOrder');

after_attempt50 = mark_attempt(baseline,50);
T50 = mock_state(50,20,baseline);
[after50,info50] = update_stage_d_canonical_results( ...
    after_attempt50,T50,'stage-d-test','append');
assert(info50.updated && after50.progress.stage_d_T50_complete);
assert(isequaln(after50.static.T20,baseline.static.T20));
assert(isequaln(after50.damping,baseline.damping));
partial50 = validate_stage_d_four_temperature_results(struct('results',after50));
assert(partial50.passed && partial50.next_temperature_C == 80);
bad_decision = after50; bad_decision.decision.allow_stage_d = true;
assert(~validate_stage_d_four_temperature_results( ...
    struct('results',bad_decision)).passed);

[after50_again,info_again] = update_stage_d_canonical_results( ...
    after50,T50,'stage-d-test','append');
assert(~info_again.updated && info_again.already_accepted);
assert(isequaln(after50_again.static.T50,after50.static.T50));

after_attempt80 = mark_attempt(after50,80);
T80 = mock_state(80,50,baseline);
[after80,~] = update_stage_d_canonical_results( ...
    after_attempt80,T80,'stage-d-test','append');
assert(validate_stage_d_four_temperature_results( ...
    struct('results',after80)).next_temperature_C == 100);
after_attempt100 = mark_attempt(after80,100);
T100 = mock_state(100,80,baseline);
[pending,~] = update_stage_d_canonical_results( ...
    after_attempt100,T100,'stage-d-test','append');
pending_validation = validate_stage_d_four_temperature_results(struct('results',pending));
assert(pending_validation.passed && pending_validation.finalization_pending);
assert(~pending.progress.stage_d_complete && ~pending.decision.allow_stage_e);

assert_error(@() update_stage_d_canonical_results(pending, ...
    struct('additional_results_check',audit(),'process_id',1001, ...
    'session_id','session-100'),'stage-d-test','finalize'), ...
    'StageD:ResultReloadFailed');
[complete,~] = update_stage_d_canonical_results(pending, ...
    struct('additional_results_check',audit(),'process_id',2002, ...
    'session_id','independent-session'),'stage-d-test','finalize');
final_validation = validate_stage_d_four_temperature_results(struct('results',complete));
assert(final_validation.passed && final_validation.stage_d_complete);
assert(complete.progress.stage_d_complete && complete.decision.allow_stage_e);
missing_reload = complete;
missing_reload.validation.stage_d = rmfield( ...
    missing_reload.validation.stage_d,'independent_reload');
assert(~validate_stage_d_four_temperature_results( ...
    struct('results',missing_reload)).passed);
bad_reload = complete;
bad_reload.validation.stage_d.independent_reload.finalize_process_id = 1001;
assert(~validate_stage_d_four_temperature_results( ...
    struct('results',bad_reload)).passed);
end

function test_failure_consumes_attempt(baseline)
attempted = mark_attempt(baseline,50);
bad_attempt = attempted; bad_attempt.progress.current_attempt_temperature_C = 80;
assert(~validate_stage_d_four_temperature_results( ...
    struct('results',bad_attempt)).passed);
failure = struct('temperature_C',50, ...
    'main_status','FOUR_TEMPERATURE_STATIC_STATE_FAILED', ...
    'failure_gate','TEST_FORMAL_GATE','diagnostic_identifier','StageD:Test', ...
    'diagnostic_message','synthetic failure');
[failed,~] = update_stage_d_canonical_results( ...
    attempted,failure,'stage-d-test','record_failure');
validation = validate_stage_d_four_temperature_results(struct('results',failed));
assert(validation.passed && validation.failed_temperature_C == 50);
assert(strcmp(failed.decision.status,'FOUR_TEMPERATURE_STATIC_STATE_FAILED'));
bad_failure = failed; bad_failure.progress.failure_gate = 'DIFFERENT_GATE';
assert(~validate_stage_d_four_temperature_results( ...
    struct('results',bad_failure)).passed);
assert_error(@() mark_attempt(failed,50),'StageD:FormalAttemptAlreadyConsumed');
assert_error(@() update_stage_d_canonical_results( ...
    failed,mock_state(50,20,baseline),'stage-d-test','append'), ...
    'StageD:FormalAttemptAlreadyConsumed');
end

