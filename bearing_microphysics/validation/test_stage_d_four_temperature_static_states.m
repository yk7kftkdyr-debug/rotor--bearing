end

function test_canonical_transaction(baseline)
temporary_directory = tempname;
mkdir(temporary_directory);
cleanup = onCleanup(@() rmdir(temporary_directory,'s'));
canonical = fullfile(temporary_directory, ...
    'thermal_4T_frequency_domain_results.mat');
results = baseline; save(canonical,'results');
directory_audit = stage_d_canonical_transaction('audit',canonical);
assert(directory_audit.passed);
payload = struct('temperature_C',50, ...
    'additional_results_check',directory_audit, ...
    'process_id',3003,'session_id','transaction-session');
[attempted,~] = update_stage_d_canonical_results( ...
    baseline,payload,'stage-d-test','mark_attempt');
saved = stage_d_canonical_transaction('save',canonical,attempted);
assert(saved.results.progress.stage_d_transaction_sequence == 1);
assert_error(@() stage_d_canonical_transaction('save',canonical,attempted), ...
    'StageD:CanonicalResultArtifactConflict');
gap = attempted; gap.progress.stage_d_transaction_sequence = 3;
assert_error(@() stage_d_canonical_transaction('save',canonical,gap), ...
    'StageD:CanonicalResultArtifactConflict');
failure = struct('temperature_C',50, ...
    'main_status','FOUR_TEMPERATURE_STATIC_STATE_FAILED', ...
    'failure_gate','TRANSACTION_RECOVERY_TEST', ...
    'diagnostic_identifier','StageD:TransactionTest', ...
    'diagnostic_message','synthetic transaction recovery');
[results,~] = update_stage_d_canonical_results( ...
    saved.results,failure,'stage-d-test','record_failure');
source = java.nio.file.Paths.get(canonical,javaArray('java.lang.String',0));
options = javaArray('java.nio.file.OpenOption',1);
options(1) = java.nio.file.StandardOpenOption.WRITE;
channel = java.nio.channels.FileChannel.open(source,options);
file_lock = channel.tryLock();
assert_error(@() stage_d_canonical_transaction('save',canonical,results), ...
    'StageD:CanonicalResultArtifactConflict');
file_lock.release(); channel.close();
transaction = [canonical '.stage_d_transaction.mat'];
save(transaction,'results');
stage_d_canonical_transaction('recover',canonical);
recovered = load(canonical);
assert(recovered.results.progress.stage_d_transaction_sequence == 2);
assert(~isfile(transaction));
results = attempted; save(transaction,'results');
stage_d_canonical_transaction('recover',canonical);
assert(~isfile(transaction));
junk = 1; save(transaction,'junk');
stage_d_canonical_transaction('recover',canonical);
assert(~isfile(transaction));
valid_results = recovered.results;
save(canonical,'junk');
results = valid_results; save(transaction,'results');
stage_d_canonical_transaction('recover',canonical);
assert(validate_stage_d_four_temperature_results(load(canonical)).passed);
invalid_directory = fullfile(temporary_directory,'invalid_pair'); mkdir(invalid_directory);
invalid_canonical = fullfile(invalid_directory,'thermal_4T_frequency_domain_results.mat');
save(invalid_canonical,'junk'); save([invalid_canonical '.stage_d_transaction.mat'],'junk');
assert_error(@() stage_d_canonical_transaction('recover',invalid_canonical), ...
    'StageD:CanonicalResultArtifactConflict');
extra = fullfile(temporary_directory,'unexpected.mat'); save(extra,'junk');
assert(~stage_d_canonical_transaction('audit',canonical).passed);
delete(extra);
assert(stage_d_canonical_transaction('audit',canonical).passed);
end

function test_source_scope(repository_root)
runner = fileread(fullfile(repository_root, ...
    'run_stage_d_build_four_temperature_static_states.m'));
solver = fileread(fullfile(repository_root, ...
    'solve_stage_d_static_temperature_case.m'));
transaction = fileread(fullfile(repository_root,'stage_d_canonical_transaction.m'));
combined = [runner newline solver newline transaction];
assert(isempty(regexpi(combined,'\<newmark\w*\s*\(','once')));
assert(isempty(regexpi(combined, ...
    '\<(frequency_response|frf|run_thermal_outer_loop_4cases)\w*\s*\(','once')));
assert(isscalar(regexp(solver, ...
    'solve_thermal_mechanical_outer_loop\s*\(','match')));
assert(isempty(regexp(solver, ...
    'solve_thermal_mechanical_outer_loop\s*\([^\n]*,\s*20\s*,','once')));
assert(contains(runner,"'git rev-parse HEAD^'"));
assert(contains(runner,"'record_timeout'"));
assert(contains(runner,"stage_d_canonical_transaction('save'"));
assert(contains(transaction,'java.nio.file.StandardCopyOption.ATOMIC_MOVE'));
assert(contains(transaction,"'.stage_d_transaction.mat'"));
end

