function assert_error(callback,identifier)
try
    callback();
catch exception
    assert(strcmp(exception.identifier,identifier), ...
        'Unexpected identifier: %s',exception.identifier);
    return;
end
error('StageD:ExpectedError','Expected %s.',identifier);
end
