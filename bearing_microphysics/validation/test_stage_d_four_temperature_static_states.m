function test_bearing_statistics
stats = compute_stage_d_bearing_statistics([0 2 4 0],[0 pi/2 pi 3*pi/2]);
assert(isequal(stats.loaded_indices,[2 3]) && stats.loaded_count == 2);
assert(abs(stats.load_zone_angle_rad-pi/2) <= eps(pi));
assert(stats.max_load_element_index == 3);
assert(stats.Q_max_N == 4 && stats.Q_mean_loaded_N == 3 && stats.Q_sum_N == 6);
assert(abs(stats.Q_std_loaded_N-sqrt(2)) <= 10*eps);
assert(abs(stats.CV_Q-sqrt(2)/3) <= 10*eps);
roller = compute_stage_d_bearing_statistics([1 2;0 0;3 1],[0 2*pi/3 4*pi/3]);
assert(isequal(roller.rolling_element_loads_N,[3 0 4]));
assert(isequal(roller.loaded_indices,[1 3]));
end

