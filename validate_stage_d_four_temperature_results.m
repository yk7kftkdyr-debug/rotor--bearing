function validation = validate_stage_d_four_temperature_results(artifact)
%VALIDATE_STAGE_D_FOUR_TEMPERATURE_RESULTS Validate partial/final canonical MAT.

checks = struct();
checks.top_level = isstruct(artifact) && isequal(fieldnames(artifact),{'results'});
if ~checks.top_level, validation = finish(checks); return; end
r = artifact.results;
required = {'meta','configuration','progress','static','modal','damping', ...
    'validation','decision'};
checks.schema = isstruct(r) && all(isfield(r,required)) && ...
    isfield(r.static,'T20') && isfield(r.modal,'T20');
if ~checks.schema, validation = finish(checks); return; end

checks.identity = identity_valid(r);
initialized = stage_d_initialized(r);
if initialized
    checks.stage_c_baseline = true;
else
    stage_c = validate_stage_c_fixed_damping_envelope(artifact);
    checks.stage_c_baseline = stage_c.passed;
end
checks.T20 = T20_valid(r.static.T20);
[summary,summary_valid] = frozen_summary(r);
checks.frozen_summary = summary_valid;
stored_reference_exists = initialized && isfield(r.validation,'stage_d') && ...
    isfield(r.validation.stage_d,'frozen_stage_c_reference');
if stored_reference_exists
    checks.frozen_stage_c = isequaln(summary, ...
        r.validation.stage_d.frozen_stage_c_reference);
else
    checks.frozen_stage_c = ~initialized;
end

temperatures = [50 80 100]; completed = zeros(1,0);
checks.sequence = true; checks.cases = true; checks.source_commit = true;
for k = 1:3
    field = sprintf('T%d',temperatures(k));
    if isfield(r.static,field)
        if k > 1 && ~isfield(r.static,sprintf('T%d',temperatures(k-1)))
            checks.sequence = false;
        end
        case_validation = validate_stage_d_static_temperature_case( ...
            r.static.(field),r.meta.model_dof_count);
        checks.cases = checks.cases && case_validation.passed;
        checks.source_commit = checks.source_commit && ...
            isfield(r.meta,'stage_d_source_commit') && ...
            strcmp(char(r.static.(field).source_commit), ...
            char(r.meta.stage_d_source_commit));
        completed(end+1) = temperatures(k); %#ok<AGROW>
    elseif any(arrayfun(@(later) isfield(r.static,sprintf('T%d',later)), ...
            temperatures(k+1:end)))
        checks.sequence = false;
    end
end
expected_completed = temperatures(1:numel(completed));
checks.completed_prefix = isequal(completed,expected_completed);
all_static_states_accepted = isequal(completed,temperatures);
if isempty(completed), next_temperature = 50;
elseif all_static_states_accepted, next_temperature = NaN;
else, next_temperature = temperatures(numel(completed)+1);
end

[progress_pass,failed_temperature] = progress_valid( ...
    r.progress,completed,all_static_states_accepted,initialized);
checks.progress = progress_pass;
checks.failure_metadata = ~initialized || failure_metadata_valid(r,failed_temperature);
finalized = logical_scalar(r.progress,'stage_d_complete',true);
checks.stage_d_audit = ~initialized || stage_d_audit_valid(r,finalized);
forbidden_fields = {'response','frequency_response','newmark','newmark_result', ...
    'dynamic','dynamic_results','time_response'};
checks.forbidden_outputs = logical_scalar(r.meta,'newmark_used',false) && ...
    logical_scalar(r.meta,'dynamic_ehl_used',false) && ...
    logical_scalar(r.meta,'old_ehl_used_in_formal_response',false) && ...
    ~any(isfield(r,forbidden_fields)) && ...
    r.damping.old_ehl_excluded && r.damping.legacy_rayleigh_excluded;
checks.decision = ~initialized || decision_valid(r,all_static_states_accepted, ...
    finalized,failed_temperature);

validation = finish(checks);
validation.completed_temperature_C = [20 completed];
validation.next_temperature_C = next_temperature;
validation.all_static_states_accepted = all_static_states_accepted;
validation.stage_d_complete = all_static_states_accepted && finalized;
validation.finalization_pending = all_static_states_accepted && ~finalized;
validation.failed_temperature_C = failed_temperature;
validation.frozen_damping_unchanged = checks.frozen_stage_c;
validation.frozen_stage_c_summary = summary;
end

function pass = identity_valid(r)
meta = r.meta;
fields = {'branch','baseline_commit','stage_b_commit','source_commit', ...
    'model_dof_count'};
pass = isstruct(meta) && all(isfield(meta,fields)) && ...
    strcmp(char(meta.branch),'thermal-equivalent-damping-frequency-domain-v1') && ...
    strcmp(char(meta.baseline_commit),'2a135aeb99ab4751154f18051b473cc6a7e463fb') && ...
    strcmp(char(meta.stage_b_commit),'d059b5684eefee63fbc2dda57ea9c8b3342afc32') && ...
    strcmp(char(meta.source_commit),'51a1da02819f3d7af5b7dcbe070d6ee669442af3') && ...
    isequal(meta.model_dof_count,192);
end

function pass = T20_valid(value)
required = {'q_static','thermal_state','bearing_state_front', ...
    'bearing_state_rear','M','G','K_tangent_original','dof_mapping', ...
    'bearing_mapping','observation_mapping','formal_acceptance', ...
    'acceptance_residuals'};
pass = isstruct(value) && all(isfield(value,required)) && ...
    isequal(size(value.q_static),[192 1]) && all(isfinite(value.q_static)) && ...
    valid_square(value.M,192) && valid_square(value.G,192) && ...
    valid_square(value.K_tangent_original,192) && value.formal_acceptance && ...
    thermal_pair_valid(value.thermal_state) && ...
    bearing_state_valid(value.bearing_state_front) && ...
    bearing_state_valid(value.bearing_state_rear) && ...
    isstruct(value.dof_mapping) && ...
    isequal(value.dof_mapping.model_dof_count,192) && ...
    isstruct(value.bearing_mapping) && value.bearing_mapping.validated && ...
    isstruct(value.observation_mapping) && value.observation_mapping.validated && ...
    t20_acceptance_valid(value.acceptance_residuals);
end

function pass = thermal_pair_valid(value)
pass = isstruct(value) && all(isfield(value,{'ball','roller'})) && ...
    thermal_entry_valid(value.ball) && thermal_entry_valid(value.roller);
end

function pass = thermal_entry_valid(value)
fields = {'T_oil','T_final','T_film','T_inner','T_outer','T_element', ...
    'eta','alpha_p','working_clearance','film_thickness'};
pass = isstruct(value) && all(isfield(value,fields));
if ~pass, return; end
numbers = cellfun(@(name) value.(name),fields,'UniformOutput',false);
pass = all(cellfun(@(number) isnumeric(number) && isscalar(number) && ...
    isreal(number) && isfinite(number),numbers)) && value.eta > 0 && ...
    value.alpha_p > 0 && value.film_thickness > 0 && value.T_oil == 20;
end

function pass = bearing_state_valid(value)
fields = {'theta','Q','delta','loaded_count','loaded_index','film', ...
    'Fx','Fy','Fz','Mx','My'};
pass = isstruct(value) && all(isfield(value,fields)) && ...
    isnumeric(value.Q) && isnumeric(value.delta) && ...
    isequal(size(value.Q),size(value.delta)) && ...
    all(isfinite(value.Q),'all') && all(value.Q >= 0,'all') && ...
    all(isfinite(value.delta),'all') && all(value.delta >= 0,'all') && ...
    all(isfinite([value.Fx value.Fy value.Fz value.Mx value.My])) && ...
    angle_count_matches(value.Q,value.theta) && ...
    isstruct(value.film) && all(isfield(value.film, ...
    {'h_m','loaded_mask','hmin_m'})) && ...
    isequal(value.film.loaded_mask,value.Q > 0) && ...
    all(isfinite(value.film.h_m(value.film.loaded_mask))) && ...
    all(value.film.h_m(value.film.loaded_mask) > 0) && ...
    isfinite(value.film.hmin_m) && value.film.hmin_m > 0;
if ~pass, return; end
aggregated = aggregate_loads(value.Q,value.theta);
loaded = aggregated > 0;
pass = value.loaded_count == nnz(loaded) && ...
    isequal(reshape(value.loaded_index,1,[]),find(loaded));
end

function pass = angle_count_matches(Q,theta)
pass = (isvector(Q) && numel(Q) == numel(theta)) || ...
    (~isvector(Q) && (size(Q,1) == numel(theta) || size(Q,2) == numel(theta)));
end

function loads = aggregate_loads(Q,theta)
if isvector(Q), loads = reshape(Q,1,[]);
elseif size(Q,1) == numel(theta), loads = reshape(sum(Q,2),1,[]);
else, loads = reshape(sum(Q,1),1,[]);
end
end

function pass = t20_acceptance_valid(value)
fields = {'mechanical_residual','thermal_residual_front_C', ...
    'thermal_residual_rear_C','thermal_residual_max_C','power_residual_W', ...
    'KKT_residual_norm','KKT_normalized_residual','constraint_residual_m', ...
    'complementarity_residual', ...
    'active_set_consistent','thermal_outer_iterations', ...
    'static_Newton_iterations','final_consistency_recompute_count'};
pass = isstruct(value) && all(isfield(value,fields)) && ...
    all(isfinite([value.mechanical_residual,value.thermal_residual_front_C, ...
    value.thermal_residual_rear_C,value.thermal_residual_max_C, ...
    value.power_residual_W,value.KKT_residual_norm, ...
    value.KKT_normalized_residual,value.constraint_residual_m])) && ...
    value.mechanical_residual <= 1e-6 && value.thermal_residual_max_C <= 1e-3 && ...
    value.power_residual_W <= 0.12 && value.KKT_normalized_residual <= 1e-6 && ...
    value.constraint_residual_m <= 1e-8 && value.active_set_consistent && ...
    isstruct(value.complementarity_residual) && ...
    ~value.complementarity_residual.available && ...
    strcmp(value.complementarity_residual.status,'NOT_PROVIDED_BY_FORMAL_SOLVER') && ...
    value.final_consistency_recompute_count == 1;
end

function [summary,pass] = frozen_summary(r)
required_damping = {'alpha','beta','K_ref_20C','C_rayleigh_ref_LOW', ...
    'C_rayleigh_ref_NOMINAL','C_rayleigh_ref_HIGH','C_formal_LOW', ...
    'C_formal_NOMINAL','C_formal_HIGH','old_ehl_excluded', ...
    'legacy_rayleigh_excluded','frozen_across_temperatures'};
pass = all(isfield(r.damping,required_damping)) && ...
    isfield(r.modal,'T20') && isfield(r.modal.T20,'anchor_modes');
if ~pass, summary = struct(); return; end
try
    summary = struct('alpha',r.damping.alpha,'beta',r.damping.beta, ...
        'anchor_modes',r.modal.T20.anchor_modes, ...
        'damping_serialized_sha256',serialized_sha256(r.damping), ...
        'anchor_modes_serialized_sha256',serialized_sha256(r.modal.T20.anchor_modes), ...
        'T20_serialized_sha256',serialized_sha256(r.static.T20), ...
        'K_ref_20C',matrix_summary(r.damping.K_ref_20C), ...
        'C_rayleigh_ref_LOW',matrix_summary(r.damping.C_rayleigh_ref_LOW), ...
        'C_rayleigh_ref_NOMINAL',matrix_summary(r.damping.C_rayleigh_ref_NOMINAL), ...
        'C_rayleigh_ref_HIGH',matrix_summary(r.damping.C_rayleigh_ref_HIGH), ...
        'C_formal_LOW',matrix_summary(r.damping.C_formal_LOW), ...
        'C_formal_NOMINAL',matrix_summary(r.damping.C_formal_NOMINAL), ...
        'C_formal_HIGH',matrix_summary(r.damping.C_formal_HIGH), ...
        'old_ehl_excluded',r.damping.old_ehl_excluded, ...
        'legacy_rayleigh_excluded',r.damping.legacy_rayleigh_excluded, ...
        'frozen_across_temperatures',r.damping.frozen_across_temperatures, ...
        'comparison','MATLAB_SERIALIZED_SHA256_AND_DETERMINISTIC_SUMMARY');
catch
    summary = struct(); pass = false; return;
end
pass = all(isfinite([summary.alpha summary.beta])) && ...
    summary.old_ehl_excluded && summary.legacy_rayleigh_excluded && ...
    summary.frozen_across_temperatures;
end

function summary = matrix_summary(A)
weights = reshape(linspace(1,2,numel(A)),size(A));
summary = struct('size',size(A),'class',class(A),'norm_fro',norm(A,'fro'), ...
    'norm_one',norm(A,1),'trace',trace(A),'sum',sum(A,'all'), ...
    'sum_abs',sum(abs(A),'all'),'max_abs',max(abs(A),[],'all'), ...
    'weighted_sum',sum(A.*weights,'all'));
end

function hash = serialized_sha256(value)
bytes = getByteStreamFromArray(value);
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(bytes);
digest = typecast(engine.digest(),'uint8');
hash = lower(reshape(dec2hex(digest,2).',1,[]));
end

function initialized = stage_d_initialized(r)
initialized = isfield(r.meta,'stage_d_source_commit') || ...
    (isfield(r.validation,'stage_d') && ...
    (isfield(r.validation.stage_d,'frozen_stage_c_reference') || ...
    isfield(r.validation.stage_d,'failure')));
attempt_fields = {'stage_d_T50_attempted','stage_d_T80_attempted', ...
    'stage_d_T100_attempted'};
initialized = initialized || any(isfield(r.progress,attempt_fields));
end

function pass = stage_d_audit_valid(r,finalized)
required = {'frozen_stage_c_reference','T20_reference_review', ...
    'additional_results_check'};
validation = r.validation;
pass = isstruct(validation) && isfield(validation,'stage_d') && ...
    all(isfield(validation.stage_d,required)) && ...
    validation.stage_d.T20_reference_review.passed && ...
    validation.stage_d.additional_results_check.passed;
if ~pass || ~finalized, return; end
if ~isfield(validation.stage_d,'independent_reload')
    pass = false; return;
end
reload = validation.stage_d.independent_reload;
reload_required = {'passed','source_commit','finalize_process_id', ...
    'finalize_session_id','last_solver_process_id','last_solver_session_id', ...
    'solver_rerun','frequency_response_run','newmark_run'};
pass = all(isfield(reload,reload_required)) && reload.passed && ...
    strcmp(reload.source_commit,r.meta.stage_d_source_commit) && ...
    positive_integer(reload.finalize_process_id) && ...
    ~isempty(reload.finalize_session_id) && ...
    reload.last_solver_process_id == r.progress.last_solver_process_id && ...
    strcmp(reload.last_solver_session_id,r.progress.last_solver_session_id) && ...
    reload.finalize_process_id ~= reload.last_solver_process_id && ...
    ~strcmp(reload.finalize_session_id,reload.last_solver_session_id) && ...
    ~reload.solver_rerun && ~reload.frequency_response_run && ~reload.newmark_run;
end

function pass = failure_metadata_valid(r,failed_temperature)
if ~isfinite(failed_temperature)
    pass = ~isfield(r.validation.stage_d,'failure');
    return;
end
failure = r.validation.stage_d.failure;
required = {'temperature_C','main_status','failure_gate','source_commit', ...
    'unaccepted_state_saved'};
pass = isstruct(failure) && all(isfield(failure,required)) && ...
    failure.temperature_C == failed_temperature && ...
    strcmp(failure.main_status,r.progress.failure_reason) && ...
    strcmp(failure.failure_gate,r.progress.failure_gate) && ...
    strcmp(failure.source_commit,r.meta.stage_d_source_commit) && ...
    ~failure.unaccepted_state_saved;
end

function pass = decision_valid(r,all_static,finalized,failed_temperature)
required = {'status','stage_d_status','stage_d_executed','allow_stage_d','allow_stage_e'};
pass = all(isfield(r.decision,required)) && ...
    logical_scalar(r.decision,'stage_d_executed',true) && ...
    logical_scalar(r.decision,'allow_stage_d',false);
if ~pass, return; end
if isfinite(failed_temperature)
    expected = r.progress.failure_reason; allow_stage_e = false;
elseif all_static && finalized
    expected = 'FOUR_TEMPERATURE_STATIC_STATES_ACCEPTED'; allow_stage_e = true;
elseif all_static
    expected = 'PENDING_INDEPENDENT_RELOAD'; allow_stage_e = false;
elseif isfinite(r.progress.current_attempt_temperature_C)
    expected = 'STAGE_D_STATIC_SOLVE_IN_PROGRESS'; allow_stage_e = false;
else
    expected = 'STAGE_D_STATIC_STATES_IN_PROGRESS'; allow_stage_e = false;
end
pass = strcmp(char(r.decision.status),expected) && ...
    strcmp(char(r.decision.stage_d_status),expected) && ...
    logical_scalar(r.decision,'allow_stage_e',allow_stage_e);
end

function [pass,failed_temperature] = progress_valid( ...
    progress,completed,all_static,initialized)
failed_temperature = NaN;
temperatures = [50 80 100];
if ~initialized
    pass = isstruct(progress) && ...
        logical_scalar(progress,'stage_c_damping_envelope_complete',true) && ...
        logical_scalar(progress,'stage_d_complete',false);
    return;
end
required = {'stage_c_damping_envelope_complete','stage_d_T50_attempted', ...
    'stage_d_T80_attempted','stage_d_T100_attempted', ...
    'stage_d_T50_complete','stage_d_T80_complete','stage_d_T100_complete', ...
    'stage_d_static_states_complete','stage_d_complete','last_completed_gate', ...
    'first_failed_temperature_C', ...
    'failure_reason','failure_gate','current_attempt_temperature_C', ...
    'current_attempt_started_at','current_attempt_process_id', ...
    'current_attempt_session_id','last_solver_process_id', ...
    'last_solver_session_id','stage_d_transaction_sequence'};
pass = isstruct(progress) && all(isfield(progress,required)) && ...
    logical(progress.stage_c_damping_envelope_complete);
if ~pass, return; end
expected_complete = ismember([50 80 100],completed);
complete_flags = logical([progress.stage_d_T50_complete, ...
    progress.stage_d_T80_complete,progress.stage_d_T100_complete]);
attempt_flags = logical([progress.stage_d_T50_attempted, ...
    progress.stage_d_T80_attempted,progress.stage_d_T100_attempted]);
attempt_prefix = [true(1,nnz(attempt_flags)) false(1,3-nnz(attempt_flags))];
pass = isequal(complete_flags,expected_complete) && ...
    isequal(attempt_flags,attempt_prefix) && all(attempt_flags >= complete_flags) && ...
    nnz(attempt_flags) <= numel(completed)+1 && ...
    logical(progress.stage_d_static_states_complete) == all_static && ...
    (~progress.stage_d_complete || all_static) && ...
    positive_integer(progress.stage_d_transaction_sequence);
if ~pass, return; end
incomplete_attempts = find(attempt_flags & ~complete_flags);
if isfinite(progress.first_failed_temperature_C)
    failed_temperature = progress.first_failed_temperature_C;
    failure_index = find([50 80 100] == failed_temperature,1);
    pass = ~isempty(failure_index) && attempt_flags(failure_index) && ...
        ~complete_flags(failure_index) && ~isempty(progress.failure_reason) && ...
        any(strcmp(progress.failure_reason,{'STATIC_TEMPERATURE_CASE_TIMEOUT', ...
        'FOUR_TEMPERATURE_STATIC_STATE_FAILED', ...
        'TEMPERATURE_TANGENT_STIFFNESS_NOT_SYMMETRIC', ...
        'FROZEN_DAMPING_ARTIFACT_CHANGED'})) && ...
        ~any(attempt_flags(failure_index+1:end)) && ~progress.stage_d_complete && ...
        isnan(progress.current_attempt_temperature_C) && ...
        datetime_missing(progress.current_attempt_started_at) && ...
        isnan(progress.current_attempt_process_id) && ...
        isempty(progress.current_attempt_session_id) && ...
        valid_finished_process(progress);
else
    pass = isnan(progress.first_failed_temperature_C) && ...
        isempty(progress.failure_reason) && isempty(progress.failure_gate);
    if ~pass, return; end
    if isempty(incomplete_attempts)
        pass = isnan(progress.current_attempt_temperature_C) && ...
            datetime_missing(progress.current_attempt_started_at) && ...
            isnan(progress.current_attempt_process_id) && ...
            isempty(progress.current_attempt_session_id) && ...
            (isempty(completed) || valid_finished_process(progress));
    else
        pass = isscalar(incomplete_attempts) && ...
            progress.current_attempt_temperature_C == temperatures(incomplete_attempts) && ...
            datetime_present(progress.current_attempt_started_at) && ...
            positive_integer(progress.current_attempt_process_id) && ...
            ~isempty(progress.current_attempt_session_id);
    end
end
end

function pass = valid_finished_process(progress)
pass = positive_integer(progress.last_solver_process_id) && ...
    ~isempty(progress.last_solver_session_id);
end

function pass = datetime_present(value)
pass = isdatetime(value) && isscalar(value) && ~isnat(value);
end

function pass = datetime_missing(value)
pass = isdatetime(value) && isscalar(value) && isnat(value);
end

function pass = positive_integer(value)
pass = isnumeric(value) && isscalar(value) && isfinite(value) && ...
    value >= 1 && value == floor(value);
end

function pass = valid_square(value,n)
pass = isnumeric(value) && isreal(value) && isequal(size(value),[n n]) && ...
    all(isfinite(value),'all');
end

function pass = logical_scalar(value,name,expected)
pass = isstruct(value) && isfield(value,name) && isscalar(value.(name)) && ...
    (islogical(value.(name)) || isnumeric(value.(name))) && ...
    isfinite(value.(name)) && logical(value.(name)) == expected;
end

function validation = finish(checks)
values = struct2cell(checks);
validation = struct('passed',all(cellfun(@(v) islogical(v) && isscalar(v) && v,values)), ...
    'checks',checks,'completed_temperature_C',[],'next_temperature_C',NaN, ...
    'all_static_states_accepted',false,'stage_d_complete',false, ...
    'finalization_pending',false,'failed_temperature_C',NaN, ...
    'frozen_damping_unchanged',false,'frozen_stage_c_summary',struct());
end
