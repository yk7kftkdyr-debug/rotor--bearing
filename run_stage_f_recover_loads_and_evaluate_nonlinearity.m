function output = merge_scan_and_gate(scan,harmonics,recovered)
output = scan;
for name = fieldnames(harmonics).'
    output.(name{1}) = harmonics.(name{1});
end
values = recovered.slice_level.r_delta_slice( ...
    recovered.slice_level.loaded_mask_static_slice);
if isempty(values), maximum = NaN; else, maximum = max(values); end
loss = any(recovered.slice_level.potential_contact_loss_slice(:));
hard = loss || (isfinite(maximum) && maximum > 0.20) || ...
    output.active_set_changed || output.epsilon_NL > 0.10 || ...
    output.H2_H1 > 0.10 || output.H3_H1 > 0.10;
strong = ~hard && (~isfinite(maximum) || maximum <= 0.10) && ...
    output.epsilon_NL <= 0.05 && output.H2_H1 <= 0.05 && output.H3_H1 <= 0.05;
if hard
    status = 'REPRESENTATIVE_NONLINEAR_VALIDATION_REQUIRED';
elseif strong
    status = 'FREQUENCY_DOMAIN_LINEARIZATION_ACCEPTED';
else
    status = 'FREQUENCY_DOMAIN_LINEARIZATION_CAUTION';
end
output.maximum_r_delta_nominal = maximum;
output.potential_contact_loss_nominal = loss;
output.gate_status = status;
end

function [hard,strong,trigger] = accumulate_load_gate( ...
        hard,strong,trigger,recovered,temperature,scenario,bearing)
loss = find(recovered.slice_level.potential_contact_loss_slice,1);
limit = find(recovered.slice_level.r_delta_slice > 0.20 & ...
    recovered.slice_level.loaded_mask_static_slice,1);
value = recovered.hard_gate.maximum_loaded_slice_r_delta;
strong = strong && (~isfinite(value) || value <= 0.10);
if ~isempty(loss) || ~isempty(limit)
    hard = true;
    if isempty(trigger)
        if ~isempty(loss)
            index = loss; metric = 'POTENTIAL_CONTACT_LOSS';
            trigger_value = recovered.slice_level.Qmin_linear_slice(index);
            threshold = 0;
        else
            index = limit; metric = 'LOCAL_LINEARITY_LIMIT_EXCEEDED';
            trigger_value = recovered.slice_level.r_delta_slice(index);
            threshold = 0.20;
        end
        [roller_index,slice_index] = ind2sub( ...
            size(recovered.slice_level.loaded_mask_static_slice),index);
        trigger = struct('temperature_case_C',temperature,'scenario',scenario, ...
            'bearing',bearing,'roller_index',roller_index, ...
            'slice_index',slice_index,'metric',metric, ...
            'phase_index',NaN,'phase_rad',NaN, ...
            'slice_indices',slice_index,'trigger_value',trigger_value, ...
            'threshold',threshold,'temperature',temperature,'phase',NaN, ...
            'roller_id',roller_index,'slice_id',slice_index);
    end
end
end

function [hard,strong,trigger] = accumulate_scan_gate( ...
        hard,strong,trigger,gate,temperature,bearing)
failed = strcmp(gate.gate_status,'REPRESENTATIVE_NONLINEAR_VALIDATION_REQUIRED');
strong = strong && strcmp(gate.gate_status,'FREQUENCY_DOMAIN_LINEARIZATION_ACCEPTED');
if failed
    hard = true;
    if isempty(trigger)
        if gate.active_set_changed
            metric = 'ACTIVE_CONTACT_SET_CHANGED';
            change = gate.first_active_set_change;
            phase_index = change.phase_index; phase_rad = change.phase_rad;
            slice_indices = change.slice_indices; trigger_value = 1; threshold = 0;
            [roller_ids,slice_ids] = decode_active_contact_indices( ...
                bearing,slice_indices);
            roller_index = roller_ids(1); slice_index = slice_ids(1);
        elseif gate.epsilon_NL > 0.10
            metric = 'EPSILON_NL';
            phase_index = NaN; phase_rad = NaN; slice_indices = [];
            trigger_value = gate.epsilon_NL; threshold = 0.10;
            roller_ids = []; slice_ids = [];
            roller_index = NaN; slice_index = NaN;
        elseif gate.H2_H1 > 0.10
            metric = 'H2_H1';
            phase_index = NaN; phase_rad = NaN; slice_indices = [];
            trigger_value = gate.H2_H1; threshold = 0.10;
            roller_ids = []; slice_ids = [];
            roller_index = NaN; slice_index = NaN;
        else
            metric = 'H3_H1';
            phase_index = NaN; phase_rad = NaN; slice_indices = [];
            trigger_value = gate.H3_H1; threshold = 0.10;
            roller_ids = []; slice_ids = [];
            roller_index = NaN; slice_index = NaN;
        end
        trigger = struct('temperature_case_C',temperature,'scenario','NOMINAL', ...
            'bearing',bearing,'roller_index',roller_index, ...
            'slice_index',slice_index,'metric',metric, ...
            'phase_index',phase_index,'phase_rad',phase_rad, ...
            'slice_indices',slice_indices,'trigger_value',trigger_value, ...
            'threshold',threshold,'temperature',temperature, ...
            'phase',phase_rad,'roller_id',roller_ids,'slice_id',slice_ids);
    end
end
end

function [roller_ids,slice_ids] = decode_active_contact_indices(bearing,linear_indices)
if strcmp(bearing,'front')
    contact_shape = [22 1];
elseif strcmp(bearing,'rear')
    contact_shape = [30 9];
else
    error('StageF:ActiveContactIndex', ...
        'STAGE_F_COMPUTATION_FAILED: unknown bearing for active-contact index.');
end
linear_indices = reshape(linear_indices,1,[]);
if isempty(linear_indices) || any(linear_indices < 1) || ...
        any(linear_indices > prod(contact_shape)) || ...
        any(linear_indices ~= floor(linear_indices))
    error('StageF:ActiveContactIndex', ...
        'STAGE_F_COMPUTATION_FAILED: invalid active-contact linear index.');
end
[roller_ids,slice_ids] = ind2sub(contact_shape,linear_indices);
roller_ids = reshape(roller_ids,1,[]);
slice_ids = reshape(slice_ids,1,[]);
end

function summary = stage_f_frozen_summary(static_state,bearing)
if strcmp(bearing,'front')
    thermal = static_state.thermal_state.ball;
elseif strcmp(bearing,'rear')
    thermal = static_state.thermal_state.roller;
else
    error('StageF:FrozenThermalSummary', ...
        'STAGE_F_COMPUTATION_FAILED: unknown bearing thermal state.');
end
contact_state = static_state.(['bearing_state_' bearing]);
summary = struct('temperature_C',thermal.T_final, ...
    'viscosity_Pa_s',thermal.eta,'clearance_m',thermal.working_clearance, ...
    'contact_state_sha256',stage_f_value_sha256(contact_state));
end

function hash = stage_f_value_sha256(value)
encoded = jsonencode(value,'ConvertInfAndNaN',true);
bytes = unicode2native(encoded,'UTF-8');
digest = java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(uint8(bytes),'int8'));
raw = typecast(digest.digest(),'uint8');
hash = lower(reshape(dec2hex(raw,2).',1,[]));
end

function hash = stage_f_file_sha256(path)
fid = fopen(path,'rb');
if fid < 0, hash = ''; return; end
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid,Inf,'*uint8');
digest = java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
raw = typecast(digest.digest(),'uint8');
hash = lower(reshape(dec2hex(raw,2).',1,[]));
end
