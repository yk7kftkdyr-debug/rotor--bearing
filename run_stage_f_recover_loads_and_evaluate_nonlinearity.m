function results = run_stage_f_recover_loads_and_evaluate_nonlinearity
%RUN_STAGE_F_RECOVER_LOADS_AND_EVALUATE_NONLINEARITY One formal Stage F run.

repository_root = fileparts(mfilename('fullpath'));
identity = require_stage_f_source(repository_root);
require_independent_validation_contract(repository_root);
canonical_path = fullfile(repository_root,'results', ...
    'thermal_equivalent_damping_frequency_domain', ...
    'thermal_4T_frequency_domain_results.mat');
expected_canonical_sha256 = ...
    '3f0e6e3b379cda670ef173682c58d17a19fc6b30f761ed59a00f3c203793abfd';
if ~isfile(canonical_path) || ...
        ~strcmp(stage_f_file_sha256(canonical_path),expected_canonical_sha256) || ...
        ~stage_f_canonical_transaction('audit',canonical_path).passed
    error('StageF:BaselineMismatch', ...
        'STAGE_F_BASELINE_MISMATCH: exact canonical Stage E artifact is required.');
end
artifact = load(canonical_path); baseline = artifact.results;
if ~stage_e_baseline_valid(baseline)
    error('StageF:BaselineMismatch', ...
        'STAGE_F_BASELINE_MISMATCH: accepted Stage E inputs are incomplete.');
end

started_at = datetime('now'); candidate = baseline;
temperatures = [20 50 80 100]; scenarios = {'LOW','NOMINAL','HIGH'};
bearings = {'front','rear'};
manifest = repmat(struct('temperature_case_C',0,'bearing','', ...
    'scenario','NOMINAL','phase_count',32,'thermal_state_frozen',true, ...
    'evaluator_function','nonlinear_bearing_force'),1,8);
manifest_index = 0; first_trigger = struct([]); global_hard = false;
global_strong = true;
for temperature = temperatures
    tf = sprintf('T%d',temperature); static_state = baseline.static.(tf);
    params = formal_frozen_parameters(baseline,static_state);
    mappings = struct();
    for bearing_index = 1:numel(bearings)
        bearing = bearings{bearing_index};
        mappings.(bearing) = build_stage_f_rolling_element_linearization_mapping( ...
            baseline,temperature,bearing);
    end
    for scenario_index = 1:numel(scenarios)
        scenario = scenarios{scenario_index};
        qhat = baseline.frequency_response.(tf).(scenario).qhat_full;
        for bearing_index = 1:numel(bearings)
            bearing = bearings{bearing_index};
            recovered = recover_stage_f_rolling_element_1X_loads( ...
                mappings.(bearing),qhat);
            recovered.stage_f_source_commit = identity.source_commit;
            recovered.static_state_source_commit = ...
                baseline.meta.stage_d_source_commit;
            recovered.contact_force_resultant = ...
                recovered.contact_load_resultant;
            candidate.bearing_contact.(tf).(scenario).(bearing) = recovered;
            [global_hard,global_strong,first_trigger] = accumulate_load_gate( ...
                global_hard,global_strong,first_trigger,recovered, ...
                temperature,scenario,bearing);
        end
    end
    for bearing_index = 1:numel(bearings)
        bearing = bearings{bearing_index}; mapping = mappings.(bearing);
        evaluator = formal_evaluator( ...
            repository_root,baseline,static_state,tf,params);
        request = struct( ...
            'evaluation_mode','FORMAL_FROZEN_NONLINEAR_BEARING_FORCE', ...
            'scenario','NOMINAL','phase_count',32, ...
            'temperature_case_C',temperature,'bearing',bearing, ...
            'bearing_index',bearing_index,'q_static',static_state.q_static, ...
            'qhat_full',baseline.frequency_response.(tf).NOMINAL.qhat_full, ...
            'mapping_snapshot',mapping,'formal_parameters',params, ...
            'frozen_thermal_state',static_state.thermal_state, ...
            'contact_state_snapshot',static_state.(['bearing_state_' bearing]), ...
            'static_state_source',['results.static.' tf], ...
            'response_source',['results.frequency_response.' tf '.NOMINAL.qhat_full'], ...
            'thermal_state_source',['results.static.' tf '.thermal_state'], ...
            'canonical_sha256',expected_canonical_sha256, ...
            'thermal_state_frozen',true,'thermal_update_allowed',false, ...
            'static_resolve_allowed',false,'frequency_resolve_allowed',false);
        thermal_before = stage_f_frozen_summary(static_state,bearing);
        scan = evaluate_stage_f_nonlinear_bearing_force_scan(request,evaluator);
        thermal_after = stage_f_frozen_summary(static_state,bearing);
        harmonics = compute_stage_f_bearing_force_harmonics( ...
            scan.exact_dynamic_force_history,scan.phase_values_rad);
        gate = merge_scan_and_gate(scan,harmonics, ...
            candidate.bearing_contact.(tf).NOMINAL.(bearing));
        gate.thermal_frozen_summary = struct( ...
            'before',thermal_before,'after',thermal_after);
        candidate.nonlinearity_gate.(tf).(bearing) = gate;
        manifest_index = manifest_index+1;
        manifest(manifest_index) = struct('temperature_case_C',temperature, ...
            'bearing',bearing,'scenario','NOMINAL','phase_count',32, ...
            'thermal_state_frozen',true, ...
            'evaluator_function','nonlinear_bearing_force');
        [global_hard,global_strong,first_trigger] = accumulate_scan_gate( ...
            global_hard,global_strong,first_trigger,gate,temperature,bearing);
    end
end

if global_hard
    final_gate = 'REPRESENTATIVE_NONLINEAR_VALIDATION_REQUIRED';
    allow_stage_g = false;
elseif global_strong
    final_gate = 'FREQUENCY_DOMAIN_LINEARIZATION_ACCEPTED';
    allow_stage_g = true;
else
    final_gate = 'FREQUENCY_DOMAIN_LINEARIZATION_CAUTION';
    allow_stage_g = true;
end
candidate.stage_f_execution_audit = struct('scan_requests',manifest, ...
    'scan_request_count',numel(manifest), ...
    'evaluator_function','nonlinear_bearing_force', ...
    'evaluator_source_sha256', ...
        'd82ae8cc92a1f1fb55d9d0c14da3efa196e9f085ce22abc5cdd2b345f93af5c8', ...
    'thermal_state_frozen',true,'LOW_scans',0,'HIGH_scans',0, ...
    'source_commit',identity.source_commit, ...
    'elapsed_seconds',seconds(datetime('now')-started_at));
candidate.progress.stage_f_load_recovery_complete = true;
candidate.progress.stage_f_nonlinear_scan_complete = true;
candidate.progress.stage_f_complete = true;
candidate.progress.stage_f_gate_status = final_gate;
candidate.progress.stage_f_first_trigger = first_trigger;
candidate.progress.allow_stage_g = allow_stage_g;
candidate.progress.last_completed_gate = final_gate;
candidate.decision.status = final_gate;
candidate.decision.allow_stage_g = allow_stage_g;
candidate.validation.stage_f = struct('passed',true,'gate_status',final_gate);
validation = validate_stage_f_results(candidate,baseline);
if ~validation.passed
    error('StageF:DiagnosticMismatch', ...
        'STAGE_F_DIAGNOSTIC_MISMATCH: %s',strjoin(validation.diagnostics,','));
end
candidate.validation.stage_f = validation;
if ~validate_stage_f_results(candidate,baseline).passed
    error('StageF:DiagnosticMismatch', ...
        'STAGE_F_DIAGNOSTIC_MISMATCH: saved validation record is inconsistent.');
end
stage_f_canonical_transaction('save',canonical_path,candidate, ...
    expected_canonical_sha256);
results = candidate;
end

function require_independent_validation_contract(repository_root)
transaction_source = fileread(fullfile(repository_root, ...
    'stage_f_canonical_transaction.m'));
stage_f_independent_readonly_validation = ...
    'stage_f_independent_readonly_validation';
matlab_batch_switch = '-batch';
if ~contains(transaction_source,stage_f_independent_readonly_validation) || ...
        ~contains(transaction_source,matlab_batch_switch)
    error('StageF:BaselineMismatch', ...
        ['STAGE_F_BASELINE_MISMATCH: transaction must validate its temporary ', ...
        'candidate in an independent read-only MATLAB process before commit.']);
end
end

function identity = require_stage_f_source(repository_root)
original = pwd; cleanup = onCleanup(@() cd(original)); cd(repository_root);
stage_f_change_scope_expected_files = { ...
    'bearing_microphysics/validation/test_stage_f_rolling_element_loads_and_nonlinearity_gate.m', ...
    'build_stage_f_rolling_element_linearization_mapping.m', ...
    'recover_stage_f_rolling_element_1X_loads.m', ...
    'evaluate_stage_f_nonlinear_bearing_force_scan.m', ...
    'compute_stage_f_bearing_force_harmonics.m', ...
    'validate_stage_f_results.m', ...
    'stage_f_canonical_transaction.m', ...
    'run_stage_f_recover_loads_and_evaluate_nonlinearity.m'};
parent_commit = '7be725a500f4ae3960d5af8e076b98e150fb1dce';
expected_subject = 'feat: add rolling-element load recovery and nonlinear validity gate';
[status_status,status_output] = system('git status --porcelain=v1');
[parent_status,parent_output] = system('git log -1 --format=%P HEAD');
[subject_status,subject_output] = system('git log -1 --format=%s HEAD');
[diff_status,diff_output] = system( ...
    'git diff --name-only 7be725a500f4ae3960d5af8e076b98e150fb1dce..HEAD');
[branch_status,branch_output] = system('git branch --show-current');
[commit_status,commit_output] = system('git rev-parse HEAD');
changed = strsplit(strtrim(diff_output),newline);
if isscalar(changed) && isempty(changed{1}), changed = {}; end
valid = all([status_status parent_status subject_status diff_status ...
    branch_status commit_status] == 0) && isempty(strtrim(status_output)) && ...
    strcmp(strtrim(parent_output),parent_commit) && ...
    strcmp(strtrim(subject_output),expected_subject) && ...
    strcmp(strtrim(branch_output),'thermal-equivalent-damping-frequency-domain-v1') && ...
    isequal(sort(changed),sort(stage_f_change_scope_expected_files));
if ~valid
    error('StageF:BaselineMismatch', ...
        'STAGE_F_BASELINE_MISMATCH: exact clean reviewed Stage F source is required.');
end
identity = struct('source_commit',strtrim(commit_output));
end

function pass = stage_e_baseline_valid(results)
pass = isstruct(results) && isfield(results,'meta') && ...
    isfield(results.meta,'stage_e_source_commit') && ...
    strcmp(results.meta.stage_e_source_commit, ...
        '0cab3dc49dfffc4192066402cb70302f084cb45d') && ...
    isfield(results,'progress') && isfield(results.progress,'stage_e_complete') && ...
    isequal(results.progress.stage_e_complete,true) && ...
    isfield(results,'decision') && strcmp(results.decision.status, ...
        'FOUR_TEMPERATURE_1X_RESPONSES_ACCEPTED') && ...
    isfield(results,'validation') && isfield(results.validation,'stage_e') && ...
    isequal(results.validation.stage_e.passed,true);
if ~pass, return; end
for temperature = [20 50 80 100]
    tf = sprintf('T%d',temperature);
    pass = pass && isfield(results.static,tf) && ...
        all(isfield(results.static.(tf),{'q_static','thermal_state', ...
        'bearing_state_front','bearing_state_rear'}));
    for scenario = {'LOW','NOMINAL','HIGH'}
        pass = pass && isfield(results.frequency_response.(tf),scenario{1}) && ...
            isequal(size(results.frequency_response.(tf).(scenario{1}).qhat_full),[192 1]) && ...
            all(isfinite(results.frequency_response.(tf).(scenario{1}).qhat_full));
    end
end
end

