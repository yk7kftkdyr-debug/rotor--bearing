function [reconstruction_error,pass] = recompute_force_error(force,cfg)
reconstruction_error = Inf; pass = false;
required = {'Fhat','formal_phase_forces_N','phase_rad','nonzero_dofs', ...
    'force_amplitude_N','unbalance_mass_kg','eccentricity_m','unbalance_U_kg_m', ...
    'unbalance_phase_rad','unbalance_node','mapping_source', ...
    'four_phase_reconstruction_error'};
if ~isstruct(force) || ~all(isfield(force,required)) || ...
        ~isequal(size(force.Fhat),[192 1]) || ...
        ~isequal(size(force.formal_phase_forces_N),[192 4])
    return;
end
Omega = cfg.rotational_speed_rad_s;
omega = cfg.omega_1X_rad_s;
expected_amplitude = cfg.unbalance.unbalance_kg_m*Omega^2;
phases = [0 pi/2 pi 3*pi/2];
expected_Fhat = complex(zeros(192,1));
radial_dofs = 6*cfg.unbalance.rotor_node+[-5 -4];
expected_samples = zeros(2,4);
for sample_index = 1:4
    rotor_phase = Omega*(phases(sample_index)/omega)+cfg.unbalance.phase_rad;
    expected_samples(:,sample_index) = expected_amplitude* ...
        [cos(rotor_phase);sin(rotor_phase)];
end
expected_Fhat(radial_dofs) = 0.5*(expected_samples(:,1)- ...
    expected_samples(:,3))+1i*0.5*(expected_samples(:,4)-expected_samples(:,2));
expected_phase_samples = zeros(192,4);
expected_phase_samples(radial_dofs,:) = expected_samples;
reconstructed = real(force.Fhat*exp(1i*phases));
column_error = vecnorm(reconstructed-force.formal_phase_forces_N,2,1);
column_norm = vecnorm(force.formal_phase_forces_N,2,1);
reconstruction_error = max(column_error)/max(max(column_norm),eps);
scale = max(expected_amplitude,eps);
pass = all(isfinite(force.Fhat)) && all(isfinite(force.formal_phase_forces_N),'all') && ...
    isequal(force.phase_rad,phases) && isequal(force.nonzero_dofs,radial_dofs) && ...
    norm(force.Fhat-expected_Fhat,inf) <= 1e-12*scale && ...
    norm(force.formal_phase_forces_N-expected_phase_samples,inf) <= 1e-12*scale && ...
    abs(force.Fhat(92)/force.Fhat(91)+1i) <= 1e-12 && ...
    abs(force.force_amplitude_N- ...
        cfg.unbalance.unbalance_kg_m*omega^2) <= 1e-12*scale && ...
    force.unbalance_mass_kg == cfg.unbalance.mass_kg && ...
    force.eccentricity_m == cfg.unbalance.eccentricity_m && ...
    force.unbalance_U_kg_m == cfg.unbalance.unbalance_kg_m && ...
    force.unbalance_phase_rad == cfg.unbalance.phase_rad && ...
    force.unbalance_node == cfg.unbalance.rotor_node && ...
    strcmp(force.mapping_source,'FORMAL_UNBALANCE_FORCE_SUPPORT') && ...
    reconstruction_error <= 1e-12;
end

function pass = canonical_audit_valid(audit)
pass = isstruct(audit) && logical_field(audit,'passed',true) && ...
    isfield(audit,'allowed_files') && ...
    isequal(audit.allowed_files,{'thermal_4T_frequency_domain_results.mat'}) && ...
    isfield(audit,'observed_files') && ...
    isequal(audit.observed_files,{'thermal_4T_frequency_domain_results.mat'}) && ...
    isfield(audit,'source') && strcmp(audit.source,'CANONICAL_RESULT_DIRECTORY_SCAN');
end

function pass = forbidden_flags_valid(flags)
required = {'dynamic_contact_used','newmark_used','nonlinear_bearing_used', ...
    'dynamic_ehl_used','old_ehl_used_in_formal_response'};
pass = isstruct(flags) && isequal(sort(fieldnames(flags)),sort(required.')) && ...
    all(cellfun(@(name) logical_field(flags,name,false),required));
end

function pass = logical_field(value,name,expected)
pass = isstruct(value) && isfield(value,name) && isscalar(value.(name)) && ...
    (islogical(value.(name)) || isnumeric(value.(name))) && ...
    isfinite(value.(name)) && logical(value.(name)) == expected;
end

function pass = same_numeric(a,b)
pass = isnumeric(a) && isnumeric(b) && isequal(size(a),size(b)) && ...
    all(isfinite(a),'all') && all(isfinite(b),'all') && ...
    norm(a(:)-b(:),inf) <= 1e-10*max(norm(b(:),inf),1);
end

function value = tolerance(scale)
value = 1e-10*max(abs(scale),1);
end

function validation = finish_validation(checks)
values = struct2cell(checks);
passed = all(cellfun(@(value) islogical(value) && isscalar(value) && value,values));
validation = struct('passed',passed,'checks',checks, ...
    'stage_e_complete',false,'stage_d_projection',struct('passed',false));
end
