function validation = validate_stage_e_four_temperature_1X_results(artifact)
%VALIDATE_STAGE_E_FOUR_TEMPERATURE_1X_RESULTS Validate the canonical Stage E payload.

checks = struct();
checks.top_level = isstruct(artifact) && isequal(fieldnames(artifact),{'results'});
if ~checks.top_level, validation = finish_validation(checks); return; end
r = artifact.results;
required = {'meta','configuration','progress','static','modal','damping', ...
    'validation','decision','frequency_response','complex_force', ...
    'force_definition','mapping_snapshot','mapping_audit','force_audit','modal_audits'};
checks.schema = isstruct(r) && all(isfield(r,required));
if ~checks.schema, validation = finish_validation(checks); return; end

[projection,projection_valid] = stage_d_projection(r);
if projection_valid
    stage_d_projection_validation = validate_stage_d_four_temperature_results( ...
        struct('results',projection));
else
    stage_d_projection_validation = struct('passed',false);
end
checks.stage_d_projection = projection_valid && stage_d_projection_validation.passed && ...
    stage_d_projection_validation.stage_d_complete;
progress_flags = {'stage_e_complex_force_complete','stage_e_modal_T20_complete', ...
    'stage_e_modal_T50_complete','stage_e_modal_T80_complete', ...
    'stage_e_modal_T100_complete','stage_e_T20_complete','stage_e_T50_complete', ...
    'stage_e_T80_complete','stage_e_T100_complete','stage_e_modal_audit_complete', ...
    'stage_e_complete'};
checks.progress = all(cellfun(@(name) logical_field(r.progress,name,true),progress_flags)) && ...
    isfield(r.progress,'first_failed_case') && isempty(r.progress.first_failed_case) && ...
    isfield(r.progress,'failure_reason') && isempty(r.progress.failure_reason) && ...
    isfield(r.progress,'last_completed_gate') && ...
    strcmp(char(r.progress.last_completed_gate), ...
    'STAGE_E_FOUR_TEMPERATURE_1X_RESPONSES_ACCEPTED');
snapshot = stage_e_frozen_input_snapshot(r);
[expected_damping_hashes,expected_static_hashes] = split_snapshot_hashes(snapshot.hashes);
expected_diagnostics = rebuild_response_diagnostics(r.frequency_response);
[expected_force_error,force_error_valid] = recompute_force_error( ...
    r.complex_force,r.configuration);
validation_required = {'snapshot_before','snapshot_after','damping_hashes', ...
    'static_hashes','matrices_unchanged','gyroscopic_convention', ...
    'force_reconstruction_error','response_diagnostics','units','mapping', ...
    'additional_results_check','forbidden_flags'};
checks.validation_record = isstruct(r.validation.stage_e) && ...
    logical_field(r.validation.stage_e,'passed',true) && ...
    isfield(r.validation.stage_e,'case_count') && ...
    isequal(r.validation.stage_e.case_count,12) && ...
    all(isfield(r.validation.stage_e,validation_required)) && ...
    isequaln(r.validation.stage_e.snapshot_before,snapshot) && ...
    isequaln(r.validation.stage_e.snapshot_after,snapshot) && ...
    isequaln(r.validation.stage_e.snapshot_before,r.validation.stage_e.snapshot_after) && ...
    isequaln(r.validation.stage_e.damping_hashes,expected_damping_hashes) && ...
    isequaln(r.validation.stage_e.static_hashes,expected_static_hashes) && ...
    isequal(r.validation.stage_e.matrices_unchanged,true) && ...
    isequaln(r.validation.stage_e.response_diagnostics,expected_diagnostics) && ...
    force_error_valid && ...
    isequal(r.validation.stage_e.force_reconstruction_error,expected_force_error) && ...
    strcmp(r.validation.stage_e.gyroscopic_convention, ...
    'Mddot_plus_C_plus_OmegaG_qdot_plus_Kq') && ...
    isequaln(r.validation.stage_e.mapping,r.mapping_snapshot) && ...
    strcmp(r.validation.stage_e.units,'SI') && ...
    logical_field(r.validation.stage_e.additional_results_check,'passed',true) && ...
    canonical_audit_valid(r.validation.stage_e.additional_results_check) && ...
    forbidden_flags_valid(r.validation.stage_e.forbidden_flags) && ...
    all(~struct2array(r.validation.stage_e.forbidden_flags));
checks.decision = isfield(r.decision,'stage_e_status') && ...
    strcmp(char(r.decision.status),'FOUR_TEMPERATURE_1X_RESPONSES_ACCEPTED') && ...
    strcmp(char(r.decision.stage_e_status),'FOUR_TEMPERATURE_1X_RESPONSES_ACCEPTED') && ...
    logical_field(r.decision,'allow_stage_e',false) && ...
    logical_field(r.decision,'allow_stage_f',true);
[checks.forbidden_paths,forbidden_failure_path] = forbidden_paths_absent(r);
checks.mapping_and_force = mapping_and_force_valid(r);
checks.responses = checks.mapping_and_force && responses_valid(r);
checks.modal_audits = checks.mapping_and_force && modal_audits_valid(r);

validation = finish_validation(checks);
validation.stage_e_complete = validation.passed;
validation.stage_d_projection = stage_d_projection_validation;
validation.forbidden_failure_path = forbidden_failure_path;
end

function pass = responses_valid(r)
pass = true; temperatures = [20 50 80 100]; scenarios = {'LOW','NOMINAL','HIGH'};
Omega = r.configuration.rotational_speed_rad_s;
omega = r.configuration.omega_1X_rad_s;
quality_cfg = build_equivalent_damping_frequency_domain_config();
quality_options = quality_cfg.stage_e.solve_quality;
for temperature = temperatures
    field = sprintf('T%d',temperature);
    if ~isfield(r.frequency_response,field), pass = false; return; end
    for k = 1:numel(scenarios)
        scenario = scenarios{k};
        if ~isfield(r.frequency_response.(field),scenario), pass = false; return; end
        response = r.frequency_response.(field).(scenario);
        required = {'qhat_full','rcond_Z','rhs_relative_residual', ...
            'relative_residual','relative_residual_definition', ...
            'normwise_backward_error_inf','refinement_history', ...
            'refinement_step_count','correction_relative_norm', ...
            'solver_warning_id','solver_warning_message','solve_quality_gate', ...
            'caution_flags','omega_source_match','Omega_source_match', ...
            'solver_validator_Z_relative_difference', ...
            'solver_validator_diagnostic_relative_difference','finite_solution', ...
            'norm_qhat_2','norm_qhat_inf','conditioning_flag','accepted', ...
            'solver','gyroscopic_sign_convention','gyroscopic_matrix_symmetrized', ...
            'omega_exc_rad_s','Omega_rotor_rad_s','temperature_case_C', ...
            'scenario','metrics','dynamic_contact_used','newmark_used', ...
            'nonlinear_bearing_used','frequency_exc_Hz','force_definition','Fhat', ...
            'mapping_snapshot','source_commit','schema_version','failure_gate', ...
            'bearing_interface_metrics','rotor_metrics','casing_metrics', ...
            'orbit_metrics','transfer_metrics','phase_metrics'};
        M = r.static.T20.M; G = r.static.T20.G;
        if temperature == 20, K = r.static.T20.K_tangent_original;
        else, K = r.static.(field).K_tangent; end
        C = r.damping.(['C_formal_' scenario]);
        Z = K-omega^2*M+1i*omega*(C+Omega*G);
        Fhat = r.complex_force.Fhat;
        response_Z = K-response.omega_exc_rad_s^2*M+ ...
            1i*response.omega_exc_rad_s*(C+response.Omega_rotor_rad_s*G);
        Z_relative_difference = norm(response_Z-Z,'fro')/ ...
            max(norm(Z,'fro'),realmin('double'));
        [DZ,qhat,warning_record] = independent_linear_solve(Z,Fhat);
        options = quality_options;
        options.omega_source_match = isequal(response.omega_exc_rad_s,omega);
        options.Omega_source_match = isequal(response.Omega_rotor_rad_s,Omega);
        options.solver_validator_Z_relative_difference = Z_relative_difference;
        options.solver_validator_diagnostic_relative_difference = 0;
        expected = evaluate_stage_e_linear_solve_quality( ...
            Z,Fhat,qhat,DZ,options,warning_record);
        diagnostic_relative_difference = max([ ...
            relative_scalar_difference(response.rcond_Z,expected.rcond_Z), ...
            relative_scalar_difference(response.rhs_relative_residual, ...
                expected.rhs_relative_residual), ...
            relative_scalar_difference(response.normwise_backward_error_inf, ...
                expected.normwise_backward_error_inf)]);
        expected.solver_validator_diagnostic_relative_difference = ...
            diagnostic_relative_difference;
        expected_norm_2 = norm(expected.qhat_full,2);
        expected_norm_inf = norm(expected.qhat_full,inf);
        if expected.rcond_Z < quality_options.rcond_hard_floor
            expected_conditioning = 'SEVERELY_ILL_CONDITIONED_DYNAMIC_STIFFNESS';
        elseif expected.rcond_Z < 1e-10
            expected_conditioning = 'ILL_CONDITIONED_DYNAMIC_STIFFNESS';
        else
            expected_conditioning = 'WELL_CONDITIONED';
        end
        if ~isstruct(response) || ~all(isfield(response,required)) || ...
                ~isequal(size(response.qhat_full),[192 1]) || ...
                any(~isfinite(response.qhat_full)) || ...
                ~quality_record_matches(response,expected,quality_options) || ...
                ~logical(response.finite_solution) || ~logical(response.accepted) || ...
                response.normwise_backward_error_inf > ...
                    quality_options.backward_error_hard_limit || ...
                response.rcond_Z < quality_options.rcond_hard_floor || ...
                ~isequal(response.norm_qhat_2,expected_norm_2) || ...
                ~isequal(response.norm_qhat_inf,expected_norm_inf) || ...
                response.norm_qhat_inf <= 100*eps || ...
                ~isstruct(response.solver_warning) || ...
                ~all(isfield(response.solver_warning,{'message','identifier','output'})) || ...
                ~ischar(response.solver_warning.message) || ...
                ~ischar(response.solver_warning.identifier) || ...
                ~ischar(response.solver_warning.output) || ...
                ~strcmp(response.conditioning_flag,expected_conditioning) || ...
                ~strcmp(response.solver,'backslash') || ...
                ~strcmp(response.gyroscopic_sign_convention, ...
                'Mddot_plus_C_plus_OmegaG_qdot_plus_Kq') || ...
                logical(response.gyroscopic_matrix_symmetrized) || ...
                ~isequal(response.omega_exc_rad_s,omega) || ...
                ~isequal(response.Omega_rotor_rad_s,Omega) || ...
                response.temperature_case_C ~= temperature || ...
                ~strcmp(response.scenario,scenario) || ...
                response.frequency_exc_Hz ~= r.configuration.frequency_1X_Hz || ...
                ~isequal(response.Fhat,Fhat) || ...
                ~isequaln(response.force_definition,r.force_definition) || ...
                ~isequaln(response.mapping_snapshot,r.mapping_snapshot) || ...
                ~strcmp(response.source_commit,r.meta.stage_e_source_commit) || ...
                ~isempty(response.failure_gate) || ...
                any([logical(response.dynamic_contact_used),logical(response.newmark_used), ...
                logical(response.nonlinear_bearing_used)])
            pass = false; return;
        end
        try
            expected_metrics = extract_stage_e_frequency_response_metrics( ...
                response.qhat_full,omega,r.mapping_snapshot);
        catch
            pass = false; return;
        end
        metric_names = {'bearing_interface_metrics','rotor_metrics','casing_metrics', ...
            'orbit_metrics','transfer_metrics','phase_metrics'};
        if ~isequaln(response.metrics,expected_metrics) || ...
                any(cellfun(@(name) ~isequaln(response.(name),expected_metrics.(name)), ...
                metric_names))
            pass = false; return;
        end
    end
end
end

function [DZ,qhat,warning_record] = independent_linear_solve(Z,Fhat)
if isempty(Z) || isempty(Fhat)
    error('StageE:IndependentSolve','Independent solve inputs must be nonempty.');
end
DZ = [];
qhat = [];
warning_state = warning;
warning_cleanup = onCleanup(@() warning(warning_state));
warning('on','all');
lastwarn('');
evalc("DZ = decomposition(Z,'lu'); qhat = DZ\Fhat;");
[warning_message,warning_identifier] = lastwarn;
warning_record = struct('identifier',warning_identifier, ...
    'message',warning_message);
end

function pass = quality_record_matches(response,expected,options)
numeric_fields = {'rcond_Z','rhs_relative_residual','relative_residual', ...
    'normwise_backward_error_inf','solver_validator_Z_relative_difference', ...
    'solver_validator_diagnostic_relative_difference'};
pass = all(cellfun(@(name) relative_scalar_difference( ...
    response.(name),expected.(name)) <= ...
    options.diagnostic_relative_match_tolerance,numeric_fields)) && ...
    norm(response.qhat_full-expected.qhat_full,inf)/ ...
        max(norm(expected.qhat_full,inf),realmin('double')) <= ...
        options.diagnostic_relative_match_tolerance && ...
    isequal(response.finite_solution,expected.finite_solution) && ...
    isequal(response.accepted,expected.accepted) && ...
    isequal(response.refinement_step_count,expected.refinement_step_count) && ...
    isequaln(response.refinement_history,expected.refinement_history) && ...
    isequaln(response.correction_relative_norm,expected.correction_relative_norm) && ...
    isequal(response.caution_flags,expected.caution_flags) && ...
    isequal(response.omega_source_match,expected.omega_source_match) && ...
    isequal(response.Omega_source_match,expected.Omega_source_match) && ...
    strcmp(response.relative_residual_definition, ...
        expected.relative_residual_definition) && ...
    strcmp(response.solver_warning_id,expected.solver_warning_id) && ...
    strcmp(response.solver_warning_message,expected.solver_warning_message) && ...
    strcmp(response.solve_quality_gate,expected.solve_quality_gate) && ...
    strcmp(response.solver_warning.identifier,expected.solver_warning_id) && ...
    strcmp(response.solver_warning.message,expected.solver_warning_message);
end

function difference = relative_scalar_difference(actual,expected)
if ~(isnumeric(actual) && isscalar(actual) && isfinite(actual) && ...
        isnumeric(expected) && isscalar(expected) && isfinite(expected))
    difference = Inf;
else
    difference = abs(actual-expected)/max(abs(expected),realmin('double'));
end
end

function pass = mapping_and_force_valid(r)
force = r.complex_force; mapping = r.mapping_snapshot;
[independent_error,independent_force_valid] = recompute_force_error( ...
    force,r.configuration);
pass = isstruct(force) && all(isfield(force,{'Fhat','nonzero_dofs', ...
    'formal_phase_forces_N','phase_rad','four_phase_reconstruction_error', ...
    'unbalance_mass_kg','eccentricity_m','unbalance_U_kg_m','unbalance_phase_rad', ...
    'unbalance_node','force_amplitude_N','force_amplitude_relative_error', ...
    'force_amplitude_gate_passed','mapping_source'})) && ...
    isequal(size(force.Fhat),[192 1]) && all(isfinite(force.Fhat)) && ...
    isequal(reshape(force.nonzero_dofs,1,[]),reshape(find(force.Fhat ~= 0),1,[])) && ...
    isequal(size(force.formal_phase_forces_N),[192 4]) && ...
    all(isfinite(force.formal_phase_forces_N),'all') && ...
    isfinite(force.four_phase_reconstruction_error) && ...
    force.four_phase_reconstruction_error <= 1e-12 && ...
    independent_force_valid && ...
    isequal(force.four_phase_reconstruction_error,independent_error) && ...
    isequal(force.force_amplitude_gate_passed,true) && ...
    force.force_amplitude_relative_error <= 1e-12 && ...
    isstruct(mapping) && all(isfield(mapping,{'rotor','casing', ...
    'front_relative_transform','rear_relative_transform', ...
    'mapping_validation_required','validated','requested_label','actual_node', ...
    'actual_global_dofs','mapping_source'})) && ...
    isfield(mapping.rotor,'R16') && ...
    isequal(mapping.rotor.R16,force.nonzero_dofs) && ...
    strcmp(mapping.requested_label,'R16') && mapping.actual_node == 16 && ...
    isequal(mapping.actual_global_dofs,force.nonzero_dofs) && ...
    isequal(mapping.mapping_validation_required,true) && isequal(mapping.validated,true) && ...
    isstruct(r.force_audit) && logical_field(r.force_audit,'passed',true) && ...
    isfield(r.force_audit,'R16_actual_dofs') && ...
    isequal(r.force_audit.R16_actual_dofs,[91 92]) && ...
    isfield(r.force_audit,'force_amplitude_N') && ...
    abs(r.force_audit.force_amplitude_N-force.force_amplitude_N) <= ...
    1e-12*max(force.force_amplitude_N,eps) && ...
    isfield(r.force_audit,'force_support_matches_mapping') && ...
    isequal(r.force_audit.force_support_matches_mapping,true) && ...
    isstruct(r.mapping_audit) && logical_field(r.mapping_audit,'passed',true) && ...
    isfield(r.mapping_audit,'force_nonzero_dofs') && ...
    isequal(r.mapping_audit.force_nonzero_dofs,[91 92]) && ...
    isfield(r.mapping_audit,'R16_actual_supported') && ...
    isequal(r.mapping_audit.R16_actual_supported,true);
if ~pass, return; end
definition = r.force_definition;
definition_required = {'rotational_speed_rpm','frequency_exc_Hz', ...
    'Omega_rotor_rad_s','omega_exc_rad_s','requested_label','actual_node', ...
    'unbalance_node','actual_global_dofs','unbalance_mass_kg','eccentricity_m','unbalance_U_kg_m', ...
    'phase_rad','mapping_source'};
pass = isstruct(definition) && all(isfield(definition,definition_required)) && ...
    definition.rotational_speed_rpm == 9900 && definition.frequency_exc_Hz == 165 && ...
    isequal(definition.Omega_rotor_rad_s, ...
        r.configuration.rotational_speed_rad_s) && ...
    isequal(definition.omega_exc_rad_s,r.configuration.omega_1X_rad_s) && ...
    strcmp(definition.requested_label,'R16') && definition.actual_node == 16 && ...
    definition.unbalance_node == 16 && ...
    isequal(definition.actual_global_dofs,force.nonzero_dofs) && ...
    definition.unbalance_mass_kg == force.unbalance_mass_kg && ...
    definition.eccentricity_m == force.eccentricity_m && ...
    definition.unbalance_U_kg_m == force.unbalance_U_kg_m && ...
    definition.phase_rad == force.unbalance_phase_rad && ...
    strcmp(definition.mapping_source,force.mapping_source) && ...
    definition.unbalance_mass_kg == 1e-3 && definition.eccentricity_m == 1e-3 && ...
    definition.unbalance_U_kg_m == 1e-6;
if ~pass, return; end
reconstructed = real(force.Fhat*exp(1i*force.phase_rad));
column_error = vecnorm(reconstructed-force.formal_phase_forces_N,2,1);
column_norm = vecnorm(force.formal_phase_forces_N,2,1);
expected_error = max(column_error)/max(max(column_norm),eps);
pass = abs(force.four_phase_reconstruction_error-expected_error) <= ...
    tolerance(expected_error);
if ~pass, return; end
try
    probe = zeros(192,1);
    extract_stage_e_frequency_response_metrics(probe+1i*probe, ...
        r.configuration.omega_1X_rad_s,mapping);
catch
    pass = false;
end
end

function pass = modal_audits_valid(r)
pass = isfield(r.damping,'actual_zeta_4T');
if ~pass, return; end
temperatures = [20 50 80 100]; scenarios = {'LOW','NOMINAL','HIGH'};
observation_dofs = unique([r.mapping_snapshot.rotor.R2 ...
    r.mapping_snapshot.rotor.R10 r.mapping_snapshot.casing.C2 ...
    r.mapping_snapshot.casing.C8]);
M = r.static.T20.M;
for temperature = temperatures
    field = sprintf('T%d',temperature);
    if ~isfield(r.modal_audits,field) || ...
            ~isfield(r.damping.actual_zeta_4T,field)
        pass = false; return;
    end
    audit = r.modal_audits.(field);
    if temperature == 20, K = r.static.T20.K_tangent_original;
    else, K = r.static.(field).K_tangent; end
    damping = struct('LOW',r.damping.C_formal_LOW, ...
        'NOMINAL',r.damping.C_formal_NOMINAL,'HIGH',r.damping.C_formal_HIGH);
    recomputed = compute_stage_e_temperature_modal_audit( ...
        M,K,damping,r.configuration.frequency_1X_Hz,observation_dofs);
    recomputed.temperature_case_C = temperature;
    recomputed.schema_version = 'stage-e-modal-audit-v1';
    required = {'natural_frequencies_Hz','mass_normalized_modes', ...
        'mass_normalization_error','first_six_frequency_Hz', ...
        'observation_dofs','observation_participation','actual_zeta', ...
        'nearest_below_165_Hz','nearest_above_165_Hz','frequency_1X_Hz'};
    if ~isstruct(audit) || ~all(isfield(audit,required)) || ...
            ~isequaln(audit,recomputed) || ...
            ~isequal(audit.observation_dofs,observation_dofs) || ...
            any(~isfinite(audit.natural_frequencies_Hz)) || ...
            any(audit.natural_frequencies_Hz <= 0) || ...
            size(audit.mass_normalized_modes,1) ~= 192 || ...
            size(audit.mass_normalized_modes,2) ~= numel(audit.natural_frequencies_Hz) || ...
            any(~isfinite(audit.mass_normalized_modes),'all') || ...
            abs(audit.frequency_1X_Hz-r.configuration.frequency_1X_Hz) > ...
            tolerance(r.configuration.frequency_1X_Hz)
        pass = false; return;
    end
    frequencies = reshape(audit.natural_frequencies_Hz,1,[]);
    Phi = audit.mass_normalized_modes;
    mass_error = norm(Phi.'*M*Phi-eye(size(Phi,2)),inf);
    participation = vecnorm(Phi(observation_dofs,:),2,1)./ ...
        max(vecnorm(Phi,2,1),eps);
    if abs(audit.mass_normalization_error-mass_error) > tolerance(mass_error) || ...
            mass_error > 1e-8 || ...
            ~same_numeric(audit.first_six_frequency_Hz, ...
            frequencies(1:min(6,end))) || ...
            ~same_numeric(audit.observation_participation,participation)
        pass = false; return;
    end
    omega = 2*pi*frequencies;
    expected_zeta = struct();
    for k = 1:numel(scenarios)
        scenario = scenarios{k}; C = r.damping.(['C_formal_' scenario]);
        expected_zeta.(scenario) = reshape(diag(Phi.'*C*Phi),1,[])./(2*omega);
        if ~isfield(audit.actual_zeta,scenario) || ...
                ~same_numeric(audit.actual_zeta.(scenario),expected_zeta.(scenario))
            pass = false; return;
        end
    end
    if ~zeta_struct_equal(r.damping.actual_zeta_4T.(field),expected_zeta,scenarios) || ...
            ~endpoint_valid(audit.nearest_below_165_Hz,frequencies, ...
            expected_zeta,scenarios,'below') || ...
            ~endpoint_valid(audit.nearest_above_165_Hz,frequencies, ...
            expected_zeta,scenarios,'above')
        pass = false; return;
    end
    if temperature == 20
        if ~same_numeric(frequencies,r.modal.T20.natural_frequencies_Hz) || ...
                ~same_numeric(Phi,r.modal.T20.mass_normalized_modes)
            pass = false; return;
        end
    elseif ~isfield(r.modal,field) || ~isequaln(r.modal.(field),audit)
        pass = false; return;
    end
end
end

function pass = endpoint_valid(endpoint,frequencies,zeta,scenarios,direction)
target = 165; tol = 100*eps(target);
if strcmp(direction,'below')
    candidates = find(frequencies < target-tol); [~,j] = min(target-frequencies(candidates));
else
    candidates = find(frequencies > target+tol); [~,j] = min(frequencies(candidates)-target);
end
if isempty(candidates), pass = false; return; end
index = candidates(j);
pass = isstruct(endpoint) && all(isfield(endpoint, ...
    {'mode_index','frequency_Hz','distance_Hz','actual_zeta'})) && ...
    endpoint.mode_index == index && ...
    abs(endpoint.frequency_Hz-frequencies(index)) <= tolerance(frequencies(index)) && ...
    abs(endpoint.distance_Hz-abs(frequencies(index)-target)) <= ...
    tolerance(abs(frequencies(index)-target));
if ~pass, return; end
for k = 1:numel(scenarios)
    name = scenarios{k};
    pass = pass && isfield(endpoint.actual_zeta,name) && ...
        abs(endpoint.actual_zeta.(name)-zeta.(name)(index)) <= ...
        tolerance(zeta.(name)(index));
end
end

function pass = zeta_struct_equal(actual,expected,scenarios)
pass = isstruct(actual);
for k = 1:numel(scenarios)
    name = scenarios{k};
    pass = pass && isfield(actual,name) && ...
        same_numeric(actual.(name),expected.(name));
end
end

function [pass,failure_path] = forbidden_paths_absent(r)
[pass,failure_path] = recursive_forbidden_fields_absent(r,'results');
pass = pass && ...
    logical_field(r.meta,'newmark_used',false) && ...
    logical_field(r.meta,'dynamic_ehl_used',false) && ...
    logical_field(r.meta,'old_ehl_used_in_formal_response',false) && ...
    logical_field(r.meta,'dynamic_contact_used',false) && ...
    logical_field(r.meta,'nonlinear_bearing_used',false) && ...
    isfield(r.damping,'old_ehl_excluded') && r.damping.old_ehl_excluded && ...
    isfield(r.damping,'legacy_rayleigh_excluded') && r.damping.legacy_rayleigh_excluded;
end

function [pass,failure_path] = recursive_forbidden_fields_absent(value,path)
pass = true; failure_path = '';
if any(strcmp(path,{'results.static','results.configuration', ...
        'results.validation.stage_c','results.validation.stage_d', ...
        'results.validation.runtime_legacy_equivalence', ...
        'results.validation.stage_e.snapshot_before', ...
        'results.validation.stage_e.snapshot_after'}))
    return;
end
if isstruct(value)
    for index = 1:numel(value)
        names = fieldnames(value(index));
        for k = 1:numel(names)
            name = names{k}; child = value(index).(name);
            child_path = [path '.' name];
            if strcmp(child_path,'results.configuration.nonlinearity_gate')
                continue;
            end
            lower_name = lower(name);
            allowed_false = any(strcmp(lower_name,{'newmark_used','dynamic_ehl_used', ...
                'old_ehl_used_in_formal_response','dynamic_contact_used', ...
                'nonlinear_bearing_used'}));
            if allowed_false
                if ~(isscalar(child) && (islogical(child) || isnumeric(child)) && ...
                        isfinite(child) && ~logical(child))
                    pass = false; failure_path = child_path; return;
                end
                continue;
            end
            forbidden = any(strcmp(lower_name,{'newmark','newmark_result', ...
                'time_response','dynamic','dynamic_results','contact','nonlinearity'})) || ...
                contains(lower_name,'qmax') || contains(lower_name,'qmin') || ...
                contains(lower_name,'contact_loss') || ...
                contains(lower_name,'dynamic_contact') || ...
                contains(lower_name,'nonlinear') || ...
                contains(lower_name,'dynamic_stiffness_z') || ...
                contains(lower_name,'complex_dynamic_stiffness') || ...
                any(strcmp(lower_name,{'z','z_matrix'}));
            if forbidden
                pass = false; failure_path = child_path; return;
            end
            [child_pass,child_failure] = recursive_forbidden_fields_absent(child,child_path);
            if ~child_pass
                pass = false; failure_path = child_failure; return;
            end
        end
    end
elseif iscell(value)
    for k = 1:numel(value)
        [child_pass,child_failure] = recursive_forbidden_fields_absent( ...
            value{k},sprintf('%s{%d}',path,k));
        if ~child_pass
            pass = false; failure_path = child_failure; return;
        end
    end
end
end

