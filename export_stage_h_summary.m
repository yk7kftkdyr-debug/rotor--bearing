function used = response_flag_used(results,field)
used = false;
for temperature = [20 50 80 100]
    tf = sprintf('T%d',temperature);
    for scenario = {'LOW','NOMINAL','HIGH'}
        record = results.frequency_response.(tf).(scenario{1});
        used = used || ~isfield(record,field) || logical(record.(field));
    end
end
end

