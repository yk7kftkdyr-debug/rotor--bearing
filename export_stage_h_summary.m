function rows = build_dynamic_rows(results)
metric_names = required_dynamic_metric_names();
records = results.trend_robustness.damping_envelope.records;
empty = struct('metric_name','','unit','','temperature_C',NaN, ...
    'LOW',NaN,'NOMINAL',NaN,'HIGH',NaN,'classification','');
rows = repmat(empty,1,numel(metric_names)*4); row_index = 0;
for metric_index = 1:numel(metric_names)
    metric_name = metric_names{metric_index};
    for temperature = [20 50 80 100]
        mask = strcmp({records.metric_name},metric_name) & ...
            [records.temperature_C] == temperature;
        if nnz(mask) ~= 1 || ~records(mask).valid
            error('StageH:MissingDynamicMetric','STAGE_H_INPUT_NOT_READY');
        end
        source = records(mask); row_index = row_index+1;
        rows(row_index) = struct('metric_name',metric_name, ...
            'unit',source.unit,'temperature_C',temperature, ...
            'LOW',source.LOW,'NOMINAL',source.NOMINAL,'HIGH',source.HIGH, ...
            'classification',source.classification);
    end
end
end

