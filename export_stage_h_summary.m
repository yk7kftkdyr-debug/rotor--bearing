function [report,text] = prepare_committable_summary
root = fileparts(mfilename('fullpath')); canonical = canonical_path(root);
require_exact_canonical(canonical);
artifact = load(canonical); [report,text] = build_report(artifact.results);
summary_path = fullfile(fileparts(canonical), ...
    'thermal_4T_frequency_domain_summary.txt');
write_summary_atomic(summary_path,text);
end

function [results,text] = finalize_reviewed_report
root = fileparts(mfilename('fullpath')); identity = require_reviewed_source(root);
canonical = canonical_path(root); require_exact_canonical(canonical);
artifact = load(canonical); baseline = artifact.results;
[report,text] = build_report(baseline); report.source_commit = identity.source_commit;
summary_path = fullfile(fileparts(canonical),report.summary_file);
if ~isfile(summary_path) || ~strcmp(fileread(summary_path),text)
    error('StageH:SummaryMismatch','STAGE_H_SUMMARY_MISMATCH');
end
candidate = baseline; candidate.final_report = report;
validation = validate_stage_h_final_results(candidate,baseline,text,true);
if ~validation.passed
    error('StageH:ValidationFailed','STAGE_H_VALIDATION_FAILED: %s', ...
        strjoin(validation.diagnostics,','));
end
candidate.final_report.validation = validation;
if ~validate_stage_h_final_results(candidate,baseline,text,true).passed
    error('StageH:ValidationFailed','STAGE_H_VALIDATION_FAILED: saved validation mismatch.');
end
atomic_append(canonical,candidate,baseline, ...
    'f09c66bd83ad5d416970b70e0b5dfad09b0ccb62b7432180b0f8b40aca0e1852', ...
    text,summary_path,report.summary_text_sha256);
results = candidate;
fprintf('THERMAL_FREQUENCY_DOMAIN_MAINLINE_COMPLETED\n');
end

