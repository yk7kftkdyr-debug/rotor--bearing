function rows = build_bearing_load_rows(results)
empty = struct('temperature_case_C',NaN,'scenario','','bearing','', ...
    'Qhat_max_magnitude_N',NaN,'Qmax_linear_max_N',NaN, ...
    'Qmin_linear_min_N',NaN,'dynamic_force_peak_N',NaN, ...
    'dynamic_force_rms_N',NaN,'force_semantics','');
rows = repmat(empty,1,24); row_index = 0;
for temperature = [20 50 80 100]
    tf = sprintf('T%d',temperature);
    for scenario = {'LOW','NOMINAL','HIGH'}
        scenario_name = scenario{1};
        for bearing = {'front','rear'}
            name = bearing{1}; row_index = row_index+1;
            record = results.bearing_contact.(tf).(scenario_name).(name);
            roller = record.roller_level;
            loaded = logical(roller.loaded_mask_static_roller(:));
            force = record.bearing_force_on_rotor;
            if ~any(loaded) || ~strcmp(force.force_semantics, ...
                    'FORCE_ON_ROTOR_MINUS_AQ')
                error('StageH:MissingBearingLoad','STAGE_H_INPUT_NOT_READY');
            end
            rows(row_index) = struct('temperature_case_C',temperature, ...
                'scenario',scenario_name,'bearing',name, ...
                'Qhat_max_magnitude_N',max(abs(roller.Qhat_roller(loaded))), ...
                'Qmax_linear_max_N',max(roller.Qmax_linear_roller(loaded)), ...
                'Qmin_linear_min_N',min(roller.Qmin_linear_roller(loaded)), ...
                'dynamic_force_peak_N',force.radial_force_peak, ...
                'dynamic_force_rms_N',force.radial_force_rms, ...
                'force_semantics',force.force_semantics);
        end
    end
end
end

function value = trend_value(results,metric_name,temperature)
records = results.trend_robustness.temperature_normalization.records;
mask = strcmp({records.metric_name},metric_name) & ...
    [records.temperature_C] == temperature & strcmp({records.scenario},'NOMINAL');
if nnz(mask) ~= 1 || ~records(mask).valid
    error('StageH:MissingStaticMetric','STAGE_H_INPUT_NOT_READY');
end
value = records(mask).value;
end

