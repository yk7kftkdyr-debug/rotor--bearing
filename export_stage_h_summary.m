function [output,summary_text] = export_stage_h_summary(varargin)
%EXPORT_STAGE_H_SUMMARY Build or finalize the frozen mainline report.

if nargin == 0
    [output,summary_text] = finalize_reviewed_report();
elseif nargin == 1 && isstruct(varargin{1})
    [output,summary_text] = build_report(varargin{1});
elseif nargin == 1 && strcmp(varargin{1},'prepare_summary')
    [output,summary_text] = prepare_committable_summary();
else
    error('StageH:InvalidInput','Stage H expects results, prepare_summary, or no input.');
end
end

function [report,text] = build_report(results)
require_stage_h_ready(results);
input_hash_before = protected_input_hash(results);
static_rows = build_static_rows(results);
system_stiffness_rows = build_system_stiffness_rows(results);
dynamic_rows = build_dynamic_rows(results);
load_rows = build_bearing_load_rows(results);
stage_completion = stage_completion_state(results);
trend = results.trend_robustness;
metric_names = unique({trend.temperature_normalization.records.metric_name},'stable');
sensitive = trend.damping_envelope.sensitive_metrics;
if numel(metric_names) ~= 55 || numel(sensitive) ~= 4 || ...
        any(~[trend.damping_envelope.records.valid])
    error('StageH:TrendSummaryMismatch','STAGE_H_INPUT_NOT_READY');
end
old_ehl_excluded = results.damping.old_ehl_excluded && ...
    ~results.meta.old_ehl_used_in_formal_response;
newmark_used = results.meta.newmark_used || response_flag_used(results,'newmark_used');
dynamic_ehl_used = results.meta.dynamic_ehl_used;
input_hash_after = protected_input_hash(results);
report = struct('schema_version','stage-h-final-report-v1', ...
    'source_commit','', ...
    'stage_h_input_hash_before',input_hash_before, ...
    'stage_h_input_hash_after',input_hash_after, ...
    'input_hash_match',strcmp(input_hash_before,input_hash_after), ...
    'research_model_boundary',struct( ...
    'included',{{'closed_loop_thermal_effect', ...
    'quasi_static_EHL_contact','fixed_equivalent_damping', ...
    'full_order_1X_frequency_response'}}, ...
    'dynamic_EHL_damping_model',false), ...
    'old_ehl_excluded',logical(old_ehl_excluded), ...
    'old_ehl_used_in_formal_response', ...
    logical(results.meta.old_ehl_used_in_formal_response), ...
    'newmark_used',logical(newmark_used), ...
    'dynamic_ehl_used',logical(dynamic_ehl_used), ...
    'stage_completion',stage_completion, ...
    'static_results',static_rows, ...
    'system_stiffness_results',system_stiffness_rows, ...
    'dynamic_results',dynamic_rows, ...
    'bearing_dynamic_loads',load_rows, ...
    'nonlinear_gate',trend.stage_f_interpretation, ...
    'damping_robustness',struct('metric_count',numel(metric_names), ...
    'robust_metric_count',numel(metric_names)-numel(sensitive), ...
    'sensitive_metric_count',numel(sensitive), ...
    'sensitive_metrics',{sensitive}, ...
    'sensitive_is_failure',false), ...
    'credibility',struct('high_confidence',{{'thermal_state', ...
    'film_thickness','clearance','static_load','contact_stiffness'}}, ...
    'damping_envelope',{{'vibration_amplitude','velocity', ...
    'acceleration','transmissibility','orbit'}}, ...
    'reporting_rule','NOMINAL + LOW/HIGH range', ...
    'not_studied',{{'dynamic_EHL_damping', ...
    'exact_nonlinear_periodic_response','system_2X_response', ...
    'system_3X_response'}}), ...
    'decision',struct('status', ...
    'THERMAL_FREQUENCY_DOMAIN_MAINLINE_COMPLETED', ...
    'physical_results_modified',false,'new_computation_performed',false));
if ~report.input_hash_match || ~old_ehl_excluded || newmark_used || ...
        dynamic_ehl_used || ~all(struct2array(stage_completion))
    error('StageH:InputNotReady','STAGE_H_INPUT_NOT_READY');
end
text = render_summary(report);
report.summary_file = 'thermal_4T_frequency_domain_summary.txt';
report.summary_text_sha256 = utf8_sha256(text);
end

function require_stage_h_ready(results)
ready = isstruct(results) && ~isfield(results,'final_report') && ...
    all(isfield(results,{'static','damping','frequency_response', ...
    'bearing_contact','nonlinear_validation','trend_robustness', ...
    'progress','meta'})) && ...
    isfield(results.trend_robustness,'decision') && ...
    strcmp(results.trend_robustness.decision.status, ...
    'THERMAL_TREND_ROBUSTNESS_ASSESSED');
if ~ready, error('StageH:InputNotReady','STAGE_H_INPUT_NOT_READY'); end
end

function hash = protected_input_hash(results)
projection = struct('static',results.static,'damping',results.damping, ...
    'frequency_response',results.frequency_response, ...
    'bearing_contact',results.bearing_contact, ...
    'nonlinear_validation',results.nonlinear_validation, ...
    'trend_robustness',results.trend_robustness);
hash = serialized_sha256(projection);
end

